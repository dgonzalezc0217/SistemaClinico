    public void estilo(String nombrePaciente) {
        this.setSize(701, 750);
        lbNombre.setText("Paciente: " + nombrePaciente);
        color();
        Alergia.mostrarAlergias(tblAlergia, idHistoriaClinica);
        tblAlergia.addMouseListener(new java.awt.event.MouseAdapter() {
            @Override
            public void mouseClicked(java.awt.event.MouseEvent evt) {
                int fila = tblAlergia.getSelectedRow();
                if (fila >= 0) {
                    txtSustancia.setText(tblAlergia.getValueAt(fila, 1).toString());
                    cbReaccion.setSelectedItem(tblAlergia.getValueAt(fila, 2).toString());
                    cbEstado.setSelectedItem(tblAlergia.getValueAt(fila, 3).toString());
                    txtObservacion.setText(tblAlergia.getValueAt(fila, 4).toString());
                }
            }
        });
        this.setLocationRelativeTo(this.getParent());
        cbReaccion.setEditable(false);
        cbReaccion.setEditor(
                new javax.swing.plaf.basic.BasicComboBoxEditor()
        );
        cbReaccion.setModel(new DefaultComboBoxModel<>(
                new String[]{
                    "-- Seleccione una reacción --",
                    "Urticaria / Erupción cutánea",
                    "Anafilaxia",
                    "Angioedema / Hinchazón",
                    "Dificultad respiratoria",
                    "Prurito / Picazón",
                    "Rinitis / Congestión",
                    "Gastrointestinal (Náuseas/Vómitos)",
                    "Mareo / Hipotensión",
                    "Otro"
                }
        ));
        cbEstado.setEditable(false);
        cbEstado.setEditor(
                new javax.swing.plaf.basic.BasicComboBoxEditor()
        );
        cbEstado.setModel(new DefaultComboBoxModel<>(
                new String[]{
                    "-- Seleccione un estado --",
                    "Confirmada",
                    "En verificacion",
                    "Descartada"
                }
        ));
    }

    private void quitarFiltroTabla() {
        // Verifica si la tabla tiene un filtro aplicado
        if (tblAlergia.getRowSorter() != null) {
            // Le asigna un filtro "nulo", lo que significa que borra el filtro y muestra todo
            ((javax.swing.table.TableRowSorter) tblAlergia.getRowSorter()).setRowFilter(null);
        }
    }

    private void limpiarCampos() {
        txtSustancia.setText("");
        cbReaccion.setSelectedIndex(0);
        txtObservacion.setText("");
        cbEstado.setSelectedIndex(0);
        tblAlergia.clearSelection();
    }
