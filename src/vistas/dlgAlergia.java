    private void btAñadirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btAñadirActionPerformed
        //Capturar los datos de la interfaz
        String sustancia = txtSustancia.getText().trim();
        String reaccion = cbReaccion.getSelectedItem().toString();
        String estado = cbEstado.getSelectedItem().toString();
        String observaciones = txtObservacion.getText().trim(); // Puede ir vacío o null según tu BD

        //Validación 
        if (sustancia.isEmpty() || reaccion.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Debe ingresar al menos la sustancia y la reacción.");
            return;
        }

        boolean exito = Alergia.añadirAlergia(
                sustancia, reaccion, estado, observaciones, this.idUsuario, this.idHistoriaClinica
        );
        Alergia.mostrarAlergias(tblAlergia, idHistoriaClinica);

        // 4. Evaluar el resultado
        if (exito) {
            javax.swing.JOptionPane.showMessageDialog(this, "Alergia guardada correctamente.");

            limpiarCampos();
            Alergia.mostrarAlergias(tblAlergia, idHistoriaClinica);
        }
    }//GEN-LAST:event_btAñadirActionPerformed

    private void btActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btActualizarActionPerformed
        int filaSeleccionada = tblAlergia.getSelectedRow();

        if (filaSeleccionada == -1) {
            javax.swing.JOptionPane.showMessageDialog(this, "Por favor, seleccione una alergia de la tabla para actualizar.", "Atención", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        // 2. Extraer el ID oculto (columna 0) y convertirlo a número entero
        int idAlergiaOculto = Integer.parseInt(tblAlergia.getValueAt(filaSeleccionada, 0).toString());

        // 3. Extraer los datos de los campos de texto/combobox
        String nuevaSustancia = txtSustancia.getText(); // Cambia por el nombre de tu campo
        String nuevaReaccion = cbReaccion.getSelectedItem().toString();
        String nuevoEstado = cbEstado.getSelectedItem().toString();
        String nuevasObservaciones = txtObservacion.getText();

        // 4. Llamar al método actualizar enviando el ID oculto
        Modelo.cAlergia modeloAlergia = new Modelo.cAlergia();
        boolean exito = modeloAlergia.actualizarAlergia(idAlergiaOculto, nuevaSustancia, nuevaReaccion, nuevoEstado, nuevasObservaciones);

        if (exito) {
            javax.swing.JOptionPane.showMessageDialog(this, "Alergia actualizada correctamente.");
            limpiarCampos();
            Alergia.mostrarAlergias(tblAlergia, idHistoriaClinica);
        }
    }//GEN-LAST:event_btActualizarActionPerformed

