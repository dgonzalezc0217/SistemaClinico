    private void tblAntecedentesMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblAntecedentesMouseClicked
int fila = tblAntecedentes.getSelectedRow();
        
        if (fila >= 0) {
            // Extraemos los objetos de las celdas (asumiendo que Tipo es columna 1 y Descripción es columna 2)
            Object valorTipo = tblAntecedentes.getValueAt(fila, 1);
            Object valorDescripcion = tblAntecedentes.getValueAt(fila, 2);
            
            // Validamos que no sean nulos para evitar errores
            String tipo = (valorTipo != null) ? valorTipo.toString() : "";
            String descripcion = (valorDescripcion != null) ? valorDescripcion.toString() : "";
            
            // Enviamos la información a los componentes visuales
            if(!tipo.isEmpty()) {
                cmbTipo.setSelectedItem(tipo);
            } else {
                cmbTipo.setSelectedIndex(0); 
            }
            
            txtDescripcion.setText(descripcion);
        }
    
    }//GEN-LAST:event_tblAntecedentesMouseClicked

