    private void btAñadirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btAñadirActionPerformed
    String tipo = cmbTipo.getSelectedItem().toString(); 
    String descripcion = txtDescripcion.getText().trim(); 

    if (descripcion.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "La descripción no puede estar vacía.");
        return;
    }

    // Registrar en la base de datos
    boolean exito = paciente.registrarAntecedente(tipo, descripcion, idHistoriaClinica, idUsuario);

    if (exito) {
        javax.swing.JOptionPane.showMessageDialog(this, "Antecedente registrado correctamente.");
        paciente.mostrarAntecedentes(tblAntecedentes, idHistoriaClinica); // Recargar la tabla
        limpiarCampos();
    }
    }//GEN-LAST:event_btAñadirActionPerformed

    private void btActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btActualizarActionPerformed
int filaSeleccionada = tblAntecedentes.getSelectedRow();
    
    if (filaSeleccionada == -1) {
        javax.swing.JOptionPane.showMessageDialog(this, "Por favor, selecciona un antecedente de la tabla para actualizar.");
        return;
    }

    // Extraer el ID oculto de la columna 0
    long idAntecedente = Long.parseLong(tblAntecedentes.getValueAt(filaSeleccionada, 0).toString());
    
    String tipo = cmbTipo.getSelectedItem().toString();
    String descripcion = txtDescripcion.getText().trim();

    if (descripcion.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "La descripción no puede estar vacía.");
        return;
    }

    boolean exito = paciente.actualizarAntecedente(idAntecedente, tipo, descripcion);

    if (exito) {
        javax.swing.JOptionPane.showMessageDialog(this, "Antecedente actualizado correctamente.");
        paciente.mostrarAntecedentes(tblAntecedentes, idHistoriaClinica); // Recargar la tabla
        limpiarCampos();
    }   
    }//GEN-LAST:event_btActualizarActionPerformed

