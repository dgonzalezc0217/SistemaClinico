    private void cargarServicios() {
        try {
            List<ServicioOpcion> servicios = modeloOrden.listarServiciosActivos();
            
            // Declaración sin genéricos (sin <ServicioOpcion>)
            DefaultComboBoxModel comboModel = new DefaultComboBoxModel();
            
            for (ServicioOpcion s : servicios) {
                comboModel.addElement(s);
            }
            
            cmbServicio.setModel(comboModel); 
            
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error al cargar los servicios: " + e.getMessage(), "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }

private void cmbServicioActionPerformed(java.awt.event.ActionEvent evt) {                                            
        evaluarTipoServicio();
    }

private void evaluarTipoServicio() {
        Object seleccionadoObj = cmbServicio.getSelectedItem();
        
        if (seleccionadoObj instanceof ServicioOpcion seleccionado) {
            // Se habilitan los campos de prescripción ÚNICAMENTE si es MEDICAMENTO
            boolean esMedicamento = "MEDICAMENTO".equalsIgnoreCase(seleccionado.tipo());
            
            txtDosis.setEnabled(esMedicamento);
            cmbUnidadDosis.setEnabled(esMedicamento);
            cmbVia.setEnabled(esMedicamento);
            txtFrecuencia.setEnabled(esMedicamento);
            spinnerInicio.setEnabled(esMedicamento);
            spinnerFin.setEnabled(esMedicamento);
            
            // Opcional: limpiar los datos si cambia a un examen/procedimiento
            if (!esMedicamento) {
                txtDosis.setText("");
                cmbUnidadDosis.setSelectedIndex(0);
                cmbVia.setSelectedIndex(0);
                txtFrecuencia.setText("");
            }
        }
    }

private void limpiarCamposDetalle() {
        cmbServicio.setSelectedIndex(0);
        txtCantidad.setText("");
        txtIndicaciones.setText("");
        txtDosis.setText("");
        txtFrecuencia.setText("");
        // Opcional: Reiniciar los spinners a la fecha actual
        spinnerInicio.setValue(new java.util.Date());
        spinnerFin.setValue(new java.util.Date());
    }

private void configurarTabla() {
        // Definir los nombres exactos de las 5 columnas que envía el botón Agregar
        String[] nombresColumnas = {"Servicio", "Cantidad", "Dosis", "Vía", "Frecuencia"};
        
        // Crear el modelo bloqueando la edición directa en la celda
        javax.swing.table.DefaultTableModel modeloTabla = new javax.swing.table.DefaultTableModel(null, nombresColumnas) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false; // La tabla será de solo lectura
            }
        };
        
        // Aplicar el modelo a tu JTable (asegúrate de que tu tabla se llame tblDetalles)
        tblDetalles.setModel(modeloTabla);
    }
