    private void btAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btAgregarActionPerformed
    try {
            ServicioOpcion servicioSel = (ServicioOpcion) cmbServicio.getSelectedItem();
            if (servicioSel == null) {
                javax.swing.JOptionPane.showMessageDialog(this, "Seleccione un servicio o medicamento.");
                return;
            }

            double cantidad = Double.parseDouble(txtCantidad.getText().trim());
            if (cantidad <= 0) {
                javax.swing.JOptionPane.showMessageDialog(this, "La cantidad debe ser mayor a cero.");
                return;
            }
            String indicaciones = txtIndicaciones.getText().trim();

            cOrdenMedica.DatosPrescripcion prescripcion = null;
            boolean esMedicamento = servicioSel.tipo().equals("MEDICAMENTO");

            if (esMedicamento) {
                double dosis = Double.parseDouble(txtDosis.getText().trim());
                String unidad = cmbUnidadDosis.getSelectedItem() != null ? cmbUnidadDosis.getSelectedItem().toString().trim() : "";
                String via = cmbVia.getSelectedItem() != null ? cmbVia.getSelectedItem().toString().trim() : "";
                String frecuencia = txtFrecuencia.getText().trim();

                if (cmbUnidadDosis.getSelectedIndex() <= 0 || cmbVia.getSelectedIndex() <= 0
                        || unidad.isEmpty() || via.isEmpty() || frecuencia.isEmpty()) {
                    javax.swing.JOptionPane.showMessageDialog(this, "Debe llenar dosis, unidad, vía y frecuencia para medicamentos.");
                    return;
                }

                java.time.format.DateTimeFormatter formatoUTC = java.time.format.DateTimeFormatter.ofPattern("uuuu-MM-dd HH:mm:ss");
                java.util.Date dateInicio = (java.util.Date) spinnerInicio.getValue();
                java.util.Date dateFin = (java.util.Date) spinnerFin.getValue();

                String inicioUTC = dateInicio.toInstant().atZone(java.time.ZoneOffset.UTC).format(formatoUTC);
                String finUTC = dateFin.toInstant().atZone(java.time.ZoneOffset.UTC).format(formatoUTC);

                prescripcion = new cOrdenMedica.DatosPrescripcion(dosis, unidad, via, frecuencia, inicioUTC, finUTC);
            }

            // Confirmación antes de agregar a la lista y a la tabla
            int confirmacion = javax.swing.JOptionPane.showConfirmDialog(
                    this,
                    "¿Desea agregar \"" + servicioSel.nombre() + "\" (Cantidad: " + cantidad + ") a la orden médica?",
                    "Confirmar ítem",
                    javax.swing.JOptionPane.YES_NO_OPTION,
                    javax.swing.JOptionPane.QUESTION_MESSAGE
            );

            if (confirmacion != javax.swing.JOptionPane.YES_OPTION) {
                return;
            }

            // Agregar a la lista temporal
            DetalleEntrada nuevoDetalle = new DetalleEntrada(servicioSel.idServicio(), cantidad, indicaciones, prescripcion);
            listaDetalles.add(nuevoDetalle);

            // Agregar fila a la tabla visual
            javax.swing.table.DefaultTableModel modeloTabla = (javax.swing.table.DefaultTableModel) tblDetalles.getModel();
            if (esMedicamento) {
                String dosisCompleta = txtDosis.getText().trim() + " " + cmbUnidadDosis.getSelectedItem();
                modeloTabla.addRow(new Object[]{servicioSel.nombre(), cantidad, dosisCompleta, cmbVia.getSelectedItem(), txtFrecuencia.getText().trim()});
            } else {
                modeloTabla.addRow(new Object[]{servicioSel.nombre(), cantidad, "N/A", "N/A", "N/A"});
            }

            // Limpiar formulario para el siguiente ítem
            limpiarCamposDetalle();

        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Verifique que la cantidad y la dosis sean valores numéricos.");
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error al agregar: " + e.getMessage());
        }
    }//GEN-LAST:event_btAgregarActionPerformed

    private void btLimpiarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btLimpiarActionPerformed
 if (listaDetalles.isEmpty()) {
            limpiarCamposDetalle();
            return;
        }

        int opcion = javax.swing.JOptionPane.showConfirmDialog(
                this,
                "¿Desea limpiar todos los ítems agregados a la orden?",
                "Limpiar Formulario",
                javax.swing.JOptionPane.YES_NO_OPTION,
                javax.swing.JOptionPane.QUESTION_MESSAGE
        );

        if (opcion == javax.swing.JOptionPane.YES_OPTION) {
            // Vaciar lista en memoria
            listaDetalles.clear();
            
            // Vaciar tabla visual
            javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) tblDetalles.getModel();
            model.setRowCount(0);
            
            // Limpiar campos del formulario
            cmbPrioridad.setSelectedIndex(0);
            limpiarCamposDetalle();
        }
    }//GEN-LAST:event_btLimpiarActionPerformed

    private void btFinalizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btFinalizarActionPerformed
      try {
            // 1. Validar que la lista de detalles no esté vacía
            if (listaDetalles == null || listaDetalles.isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(
                        this,
                        "Debe agregar al menos un medicamento o servicio a la orden antes de finalizar.",
                        "Orden vacía",
                        javax.swing.JOptionPane.WARNING_MESSAGE
                );
                return;
            }

            // 2. Validar que se haya elegido una prioridad válida
            if (cmbPrioridad.getSelectedIndex() <= 0) {
                javax.swing.JOptionPane.showMessageDialog(
                        this,
                        "Por favor seleccione la Prioridad de la orden.",
                        "Prioridad requerida",
                        javax.swing.JOptionPane.WARNING_MESSAGE
                );
                return;
            }

            String prioridadSeleccionada = cmbPrioridad.getSelectedItem().toString().trim();

            // 3. Confirmación del usuario
            int confirmacion = javax.swing.JOptionPane.showConfirmDialog(
                    this,
                    "¿Desea guardar y finalizar la Orden Médica?",
                    "Confirmar Orden",
                    javax.swing.JOptionPane.YES_NO_OPTION,
                    javax.swing.JOptionPane.QUESTION_MESSAGE
            );

            if (confirmacion != javax.swing.JOptionPane.YES_OPTION) {
                return;
            }

            // 4. Enviar a la base de datos a través de cOrdenMedica
            long idOrdenGuardada = modeloOrden.guardarBorrador(
                    this.idUsuarioLogueado,
                    this.idEpisodioActivo,
                    prioridadSeleccionada,
                    this.listaDetalles
            );

            // 5. Notificar éxito y cerrar la ventana
            if (idOrdenGuardada > 0) {
                javax.swing.JOptionPane.showMessageDialog(
                        this,
                        "Orden Médica N° " + idOrdenGuardada + " registrada exitosamente.",
                        "Éxito",
                        javax.swing.JOptionPane.INFORMATION_MESSAGE
                );
                this.dispose(); // Cierra el diálogo y retorna a la Historia Clínica
            }

        } catch (IllegalArgumentException e) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    e.getMessage(),
                    "Validación",
                    javax.swing.JOptionPane.WARNING_MESSAGE
            );
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Ocurrió un error al guardar la orden médica:\n" + e.getMessage(),
                    "Error de almacenamiento",
                    javax.swing.JOptionPane.ERROR_MESSAGE
            );
        }
    }//GEN-LAST:event_btFinalizarActionPerformed

