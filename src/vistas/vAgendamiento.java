    private void filtrarTabla() {

        if (sorter == null) {
            return;
        }

        final String documentoBuscado = txtCedula.getText().trim();
        final String fechaBuscada = txtFecha.getText().trim();

        Modelo.cAgendamiento.Opcion medico
                = (Modelo.cAgendamiento.Opcion) cbMedico.getSelectedItem();

        Modelo.cAgendamiento.Opcion especialidad
                = (Modelo.cAgendamiento.Opcion) cbEspecialidad.getSelectedItem();

        final long idMedico = medico == null ? 0 : medico.getId();

        final long idEspecialidad
                = especialidad == null ? 0 : especialidad.getId();

        sorter.setRowFilter(new RowFilter<DefaultTableModel, Integer>() {

            @Override
            public boolean include(
                    Entry<? extends DefaultTableModel, ? extends Integer> fila) {

                Object documentoValor = fila.getValue(4);

                String documento = documentoValor == null
                        ? ""
                        : documentoValor.toString();

                String fecha = fila.getStringValue(1);

                long medicoFila
                        = ((Number) fila.getValue(8)).longValue();

                long especialidadFila
                        = ((Number) fila.getValue(9)).longValue();

                boolean coincideDocumento
                        = documentoBuscado.isEmpty()
                        || documento.contains(documentoBuscado);

                boolean coincideFecha
                        = fechaBuscada.isEmpty()
                        || fecha.equals(fechaBuscada);

                boolean coincideMedico
                        = idMedico == 0 || medicoFila == idMedico;

                boolean coincideEspecialidad
                        = idEspecialidad == 0
                        || especialidadFila == idEspecialidad;

                return coincideDocumento
                        && coincideFecha
                        && coincideMedico
                        && coincideEspecialidad;
            }
        });
    }

    private long idCitaSeleccionada() {
        int fila = tblCitas.getSelectedRow();

        if (fila < 0) {
            throw new IllegalArgumentException(
                    "Selecciona una cita de la tabla."
            );
        }

        int filaModelo = tblCitas.convertRowIndexToModel(fila);

        return ((Number) tblCitas.getModel()
                .getValueAt(filaModelo, 0)).longValue();
    }
